//! Script prelude: header comments, schema DDL, and the bulk-load ALTER.
//!
//! Order is the replay contract: `CREATE COLLECTION`, `CREATE INDEX`,
//! `CREATE SHARD KEY`, then the raised `indexing_threshold` that keeps HNSW
//! from being rebuilt while the `UPSERT` batches land.

use qql::backend::CollectionInfo;
use qql_core::ast::ShardKey;

use crate::bulk::indexing_threshold_statement;
use crate::dump::{format_ident, generate_create_statement, generate_index_statements};

/// Header comments, schema DDL, and the bulk-load `ALTER` that precede upserts.
pub(crate) fn generate_prelude(
    collection: &str,
    info: &CollectionInfo,
    shard_keys: &[ShardKey],
    bulk_threshold_kb: u64,
) -> String {
    let mut out = String::new();
    out.push_str(&format!("-- QQL dump for {}\n", collection));
    out.push_str("-- Generated by qql dump\n\n");
    out.push_str(&format!(
        "{};\n\n",
        generate_create_statement(collection, info)
    ));

    let indexes = generate_index_statements(collection, &info.schema.payload_indexes);
    if !indexes.is_empty() {
        for idx in &indexes {
            out.push_str(&format!("{};\n", idx));
        }
        out.push('\n');
    }

    for key in shard_keys {
        out.push_str(&format!(
            "CREATE SHARD KEY {} ON COLLECTION {};\n",
            key,
            format_ident(collection)
        ));
    }
    if !shard_keys.is_empty() {
        out.push('\n');
    }

    out.push_str(&format!(
        "{};\n\n",
        indexing_threshold_statement(collection, bulk_threshold_kb)
    ));
    out
}
